// The law clerk: a conversation with a model that turns the player's plain
// English into a statute the simulation can run.
//
// The server is stateless. The browser keeps the conversation and sends it
// with each request; assistant turns come back as the raw content blocks the
// API returned and are replayed unchanged, so thinking blocks and tool calls
// stay exactly as the model produced them.
import Anthropic from '@anthropic-ai/sdk';

export const MODEL = process.env.SOCIETY_MODEL || 'claude-opus-5-5';
const EFFORT = process.env.SOCIETY_EFFORT || 'medium';

const ROLE = `You are the law clerk of a small simulated town. The player governs it - or tries to - by writing laws in plain English. Your job is to turn what they write into a statute in the simulation's own format, and to be straight with them about what the simulation can and cannot do.

The reference manual below defines the statute format and everything a statute can refer to. Each request also carries a snapshot of the town as it stands: its offices, wards, statutes in force, places and people, with the ids you must use to refer to them.

How to work:

- Translate faithfully. Compile what was asked, not what would be wise. Harsh, self-serving and foolish laws are part of the game: the point is for the player to see what happens, so do not soften, improve or moralise, and do not add safeguards they did not ask for.
- You never predict or decide outcomes. You describe mechanisms; the townspeople, who have their own preferences, do the rest. Do not write clauses that encode a result you expect.
- People's wants are not yours to set. The simulation derives everything a person wants from their own base preferences, and a statute can only see what is on the public record (age, kin, wealth, work, schooling, convictions, legal statuses), never what someone privately wants. If a law tries to target desires directly, say that it must work through such proxies and offer one.
- When the request maps cleanly onto the format, draft it and call submit_statute. Calibrate every amount against the snapshot's wages, prices and wealth.
- When part of it cannot be expressed, say so plainly: what you can implement, what you cannot and why, and the closest mechanical version. If the gap is small, draft the closest version, list what was left out in "unmodeled", and tell the player. If the gap changes what the law would do, ask before drafting.
- Ask a question only when the answer changes the mechanics in a way you cannot reasonably choose yourself. Otherwise choose, and mention the choice in a sentence.
- A statute applies to the whole town unless the player names a ward.
- After you submit, the simulation checks the draft. If it reports errors, fix them and submit again without making the player ask.

Keep replies short and plain: two to five sentences on how you read the law and any judgement calls. The player will see an exact clause-by-clause description generated by the simulation, so do not repeat the statute back to them.`;

const TOOL = {
  name: 'submit_statute',
  description: 'Submit a complete draft statute to the simulation for checking. Call this once you have a draft; call it again with a corrected draft if the simulation reports errors. The statute must follow the format in the reference manual exactly.',
  input_schema: {
    type: 'object',
    properties: {
      statute: { type: 'object', description: 'The statute, in the JSON shape the manual defines.' },
    },
    required: ['statute'],
  },
};

let client = null;
function getClient() {
  if (!client) client = new Anthropic();
  return client;
}

/** True if credentials for the API are present in the environment. */
export function available() {
  return Boolean(process.env.ANTHROPIC_API_KEY || process.env.ANTHROPIC_AUTH_TOKEN);
}

/**
 * Rebuild API messages from the browser's record of the conversation.
 *
 * history: [{ role: 'user', text } | { role: 'assistant', raw: [...blocks], verdict?: string }]
 * `verdict` is what the simulation said about the draft submitted in that
 * turn; it becomes the tool result that opens the following user turn.
 */
export function buildMessages(history, snapshot) {
  const messages = [];
  let pendingResults = [];
  let first = true;
  for (const turn of history) {
    if (turn.role === 'assistant') {
      const raw = Array.isArray(turn.raw) ? turn.raw : [{ type: 'text', text: String(turn.text || '') }];
      messages.push({ role: 'assistant', content: raw });
      pendingResults = raw
        .filter((b) => b.type === 'tool_use')
        .map((b) => ({ type: 'tool_result', tool_use_id: b.id, content: turn.verdict || 'Received.' }));
    } else {
      const content = [...pendingResults];
      pendingResults = [];
      if (first && snapshot) content.push({ type: 'text', text: `<town_snapshot>\n${snapshot}\n</town_snapshot>` });
      if (turn.text) content.push({ type: 'text', text: String(turn.text) });
      if (content.length) messages.push({ role: 'user', content });
      first = false;
    }
  }
  // A draft awaiting its verdict with no new words from the player: send the verdict alone.
  if (pendingResults.length) messages.push({ role: 'user', content: pendingResults });
  return messages;
}

/**
 * One turn of the drafting conversation.
 * Returns { reply, statute, raw, stop_reason } or throws an Error with a `status` for the HTTP layer.
 */
export async function draft({ history, snapshot, manual }) {
  const messages = buildMessages(history, snapshot);
  if (!messages.length || messages[messages.length - 1].role !== 'user') {
    throw Object.assign(new Error('the conversation must end with something for the clerk to answer'), { status: 400 });
  }
  let response;
  try {
    response = await getClient().beta.messages.create({
      model: MODEL,
      max_tokens: 16000,
      // If the model's safety classifiers decline a request, let the API retry it on the recommended fallback.
      betas: ['server-side-fallback-2026-07-01'],
      fallbacks: 'default',
      output_config: { effort: EFFORT },
      system: [{ type: 'text', text: `${ROLE}\n\n# Reference manual\n\n${manual}`, cache_control: { type: 'ephemeral' } }],
      tools: [TOOL],
      messages,
    });
  } catch (err) {
    if (err instanceof Anthropic.AuthenticationError) throw Object.assign(new Error('The API key was rejected. Check ANTHROPIC_API_KEY.'), { status: 401 });
    if (err instanceof Anthropic.PermissionDeniedError) throw Object.assign(new Error(`This API key may not use ${MODEL}. Set SOCIETY_MODEL to a model it can use.`), { status: 403 });
    if (err instanceof Anthropic.NotFoundError) throw Object.assign(new Error(`The model "${MODEL}" was not found. Set SOCIETY_MODEL to a model your key can use.`), { status: 502 });
    if (err instanceof Anthropic.RateLimitError) throw Object.assign(new Error('The clerk is being rate limited. Try again in a moment.'), { status: 429 });
    if (err instanceof Anthropic.BadRequestError) throw Object.assign(new Error(`The API rejected the request: ${err.message}`), { status: 502 });
    if (err instanceof Anthropic.APIConnectionError) throw Object.assign(new Error('Could not reach the API.'), { status: 502 });
    if (err instanceof Anthropic.APIError) throw Object.assign(new Error(`API error ${err.status}: ${err.message}`), { status: 502 });
    throw err;
  }

  if (response.stop_reason === 'refusal') {
    return { reply: 'The clerk declined to draft that. Try describing the law differently.', statute: null, raw: null, stop_reason: 'refusal' };
  }
  const reply = response.content.filter((b) => b.type === 'text').map((b) => b.text).join('\n').trim();
  const call = response.content.find((b) => b.type === 'tool_use' && b.name === TOOL.name);
  const statute = call && call.input && typeof call.input.statute === 'object' ? call.input.statute : null;
  return {
    reply: reply || (statute ? 'Here is the draft.' : response.stop_reason === 'max_tokens' ? 'The clerk ran out of room before finishing. Try a shorter or simpler law.' : ''),
    statute,
    raw: response.content,
    stop_reason: response.stop_reason,
    usage: { input: response.usage.input_tokens, output: response.usage.output_tokens, cache_read: response.usage.cache_read_input_tokens ?? 0 },
  };
}
